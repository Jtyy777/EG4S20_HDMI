// ============================================================================
// seg_decoder —— 4 位二进制 → 七段笔画码（共阳极，低电平点亮）
// ----------------------------------------------------------------------------
// seg_data[6:0] 的位序为 {g, f, e, d, c, b, a}：
//   例如 4'd0 → 7'b100_0000 —— 只有 g 段（中间横杠）为 1 不亮，其余全 0 点亮，
//   共阳管里 0 才是「亮」，所以码值恰好是「亮的段取反」。
// 0~9 为数字，A~F 为十六进制字母，default 全灭。
// 纯组合逻辑，调用方（seg_scan 之类）负责位选与扫描。
// ============================================================================
module seg_decoder
(
	input[3:0]      bin_data,
	output reg[6:0] seg_data
);

always@(*)
begin
	case(bin_data)
		4'd0:seg_data <= 7'b100_0000;
		4'd1:seg_data <= 7'b111_1001;
		4'd2:seg_data <= 7'b010_0100;
		4'd3:seg_data <= 7'b011_0000;
		4'd4:seg_data <= 7'b001_1001;
		4'd5:seg_data <= 7'b001_0010;
		4'd6:seg_data <= 7'b000_0010;
		4'd7:seg_data <= 7'b111_1000;
		4'd8:seg_data <= 7'b000_0000;
		4'd9:seg_data <= 7'b001_0000;
		4'ha:seg_data <= 7'b000_1000;
		4'hb:seg_data <= 7'b000_0011;
		4'hc:seg_data <= 7'b100_0110;
		4'hd:seg_data <= 7'b010_0001;
		4'he:seg_data <= 7'b000_0110;
		4'hf:seg_data <= 7'b000_1110;
		default:seg_data <= 7'b111_1111;
	endcase
end
endmodule
